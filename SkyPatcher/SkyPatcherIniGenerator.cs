using System.Text;
using SkyrimJPStringPatcher.Core;

namespace SkyrimJPStringPatcher.SkyPatcher;

public sealed record SkyPatcherGenerateStats(int FilesWritten, int LinesWritten, int TranslatedNames, int OriginalNames);

/// <summary>The `skypatcher-generate` command: writes SkyPatcher .ini files from translated rows.
/// The output mirrors the original files: one output file per source .ini, at the same path with
/// <see cref="SkyPatcherOutputFormat.FolderName"/> inserted after the type folder and the file name left
/// untouched (so a plugin-gated name keeps its gate). EVERY row is written, in the original line order; a
/// row without a translation goes back as its original name. That keeps the order SkyPatcher applies
/// things in — and so the winner for every record — exactly as it was, whatever else is installed. Each line
/// keeps the original filter part and sets only the name(s). Mutagen/MO2 are not involved: the rows alone
/// (a translations.tsv) are the input.</summary>
public static class SkyPatcherIniGenerator
{
    private const char FullWidthTilde = '～';

    private sealed record Row(string Key, string Mod, string RecordType, string English, string Japanese, string Notes,
        string SourcePath, string SourceFilter, int SourceLine);

    public static SkyPatcherGenerateStats Run(string translationsInputPath, string outputDir, RunLog log,
        IReadOnlyCollection<string>? modFilter = null, TraceLog? trace = null)
    {
        var files = ResolveInputFiles(translationsInputPath);
        trace?.Info($"Input: {translationsInputPath} ({files.Count} translation file(s))");

        var rows = files.SelectMany(ReadRows).ToList();
        var fromSkyPatcher = rows.Where(r => r.SourcePath.Length > 0).ToList();
        if (modFilter != null)
        {
            var wanted = new HashSet<string>(modFilter, StringComparer.OrdinalIgnoreCase);
            fromSkyPatcher = fromSkyPatcher.Where(r => wanted.Contains(r.Mod)).ToList();
        }

        var skyPatcherRoot = Path.Combine(outputDir, "SKSE", "Plugins", "SkyPatcher");
        int filesWritten = 0, linesWritten = 0, translated = 0, original = 0;
        foreach (var file in fromSkyPatcher.GroupBy(r => r.SourcePath, StringComparer.Ordinal).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            var (text, lineCount, translatedNames, originalNames) = BuildFile(file);
            var target = Path.Combine(skyPatcherRoot, OutputRelativePath(file.Key).Replace('/', Path.DirectorySeparatorChar));
            Directory.CreateDirectory(Path.GetDirectoryName(target)!);
            File.WriteAllText(target, text, new UTF8Encoding(false));
            trace?.Trace($"Wrote {target} ({lineCount} line(s))");

            filesWritten++;
            linesWritten += lineCount;
            translated += translatedNames;
            original += originalNames;
        }

        log.Section("入力", "Input");
        log.Line($"入力パス: {translationsInputPath}", $"Input path: {translationsInputPath}");
        log.Line($"読み込んだ翻訳ファイル: {files.Count}件、行 {rows.Count}（うちSkyPatcherの行 {fromSkyPatcher.Count}）",
            $"Translation files read: {files.Count}, rows {rows.Count} (SkyPatcher rows {fromSkyPatcher.Count})");
        log.Section("処理サマリ", "Processing summary");
        log.Line($"出力した.ini: {filesWritten}件、行 {linesWritten}（訳文 {translated} / 原文のまま {original}）",
            $"Files written: {filesWritten}, lines {linesWritten} (translated names {translated} / original names {original})");
        log.Line($"出力先: {skyPatcherRoot}", $"Output path: {skyPatcherRoot}");

        Console.WriteLine($"Wrote {filesWritten} SkyPatcher .ini file(s) ({linesWritten} lines: {translated} translated names, {original} original names) to: {skyPatcherRoot}");
        return new SkyPatcherGenerateStats(filesWritten, linesWritten, translated, original);
    }

    /// <summary>"armor/.Sentinel/S.ini" -> "armor/zzz_SJPTS/.Sentinel/S.ini".</summary>
    internal static string OutputRelativePath(string sourcePath)
    {
        var parts = sourcePath.Split('/').ToList();
        parts.Insert(1, SkyPatcherOutputFormat.FolderName);
        return string.Join('/', parts);
    }

    private static (string Text, int Lines, int TranslatedNames, int OriginalNames) BuildFile(IEnumerable<Row> rows)
    {
        var text = new StringBuilder();
        text.Append("; Generated by SJPTS (Skyrim JP Translation Supporter) - regenerate it from the tool; edits here are lost\r\n");

        int lines = 0, translated = 0, original = 0;
        // One output line per original line: the rows sharing a row key are the names of one line.
        foreach (var line in rows.GroupBy(r => r.Key, StringComparer.Ordinal).OrderBy(g => g.Min(r => r.SourceLine)))
        {
            var ops = line.OrderBy(r => IsShortName(r) ? 1 : 0).ToList();
            var segments = new List<string>();
            foreach (var row in ops)
            {
                var kind = IsShortName(row) ? SkyPatcherNameKind.ShortName : SkyPatcherNameKind.FullName;
                var hasTranslation = row.Japanese.Trim().Length > 0;
                if (hasTranslation)
                {
                    text.Append(SkyPatcherOutputFormat.FormatComment(kind, row.Notes, OneLine(row.English))).Append("\r\n");
                    translated++;
                }
                else
                {
                    original++;
                }
                segments.Add($"{(kind == SkyPatcherNameKind.FullName ? "fullName" : "shortName")}=~{Wrapped(hasTranslation ? row.Japanese : row.English)}~");
            }

            var filter = ops[0].SourceFilter;
            text.Append(filter.Length > 0 ? filter + ":" : "").Append(string.Join(":", segments)).Append("\r\n");
            lines++;
        }
        return (text.ToString(), lines, translated, original);
    }

    private static bool IsShortName(Row row) => row.RecordType.EndsWith(" SHRT", StringComparison.Ordinal);

    /// <summary>The name goes inside ~…~ on one line: the wrapper character cannot appear in it (the full-width
    /// tilde stands in), and a line break would end the line (a space stands in).</summary>
    private static string Wrapped(string name) => OneLine(name).Replace('~', FullWidthTilde);

    private static string OneLine(string text) =>
        text.Replace("\r\n", " ").Replace('\n', ' ').Replace('\r', ' ');

    private static List<string> ResolveInputFiles(string path)
    {
        if (File.Exists(path)) return [path];
        if (Directory.Exists(path))
            return Directory.EnumerateFiles(path, "translations.tsv", SearchOption.AllDirectories).OrderBy(f => f, StringComparer.Ordinal).ToList();
        throw new FileNotFoundException($"Translations file/directory not found: {path}");
    }

    /// <summary>Reads by column NAME, so the order of columns (and any extra ones) does not matter.</summary>
    private static IEnumerable<Row> ReadRows(string path)
    {
        var lines = File.ReadAllLines(path, Encoding.UTF8);
        if (lines.Length == 0) yield break;

        var header = lines[0].TrimStart('﻿').Split('\t');
        int Col(string name) => Array.IndexOf(header, name);
        var key = Col("FormId"); var mod = Col("WinningPlugin"); var type = Col("RecordType");
        var english = Col("EnglishText"); var japanese = Col("Japanese"); var notes = Col("Notes");
        var sourcePath = Col("SourcePath"); var sourceFilter = Col("SourceFilter"); var sourceLine = Col("SourceLine");
        if (key < 0 || mod < 0 || type < 0 || english < 0 || sourcePath < 0) yield break;   // not a SkyPatcher-capable file

        string Cell(string[] cells, int index) => index >= 0 && index < cells.Length ? TsvEscaping.Unescape(cells[index]) : "";

        foreach (var line in lines.Skip(1))
        {
            if (line.Length == 0) continue;
            var cells = line.Split('\t');
            yield return new Row(
                Cell(cells, key), Cell(cells, mod), Cell(cells, type), Cell(cells, english), Cell(cells, japanese), Cell(cells, notes),
                Cell(cells, sourcePath), Cell(cells, sourceFilter), int.TryParse(Cell(cells, sourceLine), out var n) ? n : 0);
        }
    }
}
