using SkyrimJPStringPatcher.SkyPatcher;

namespace SkyrimJPStringPatcher.Tests.SkyPatcher;

/// <summary>
/// The comment line written before each translated name in our output .ini, and read back by the
/// next scan to carry the translation forward: "; SJPTS &lt;fullName|shortName&gt; | &lt;method&gt; | &lt;original&gt;".
/// A comment line starts with ';' (grammar §2), so SkyPatcher ignores it. The original text may
/// itself contain '|', so only the first two '|' separate the fields.
/// </summary>
public class SkyPatcherOutputFormatTests
{
    [Theory]
    [InlineData(SkyPatcherNameKind.FullName, "SJPTS_TranslationLocalLlm", "Fur Coat", "; SJPTS fullName | SJPTS_TranslationLocalLlm | Fur Coat")]
    [InlineData(SkyPatcherNameKind.ShortName, "SJPTS_AutoCorpusExact", "Bob", "; SJPTS shortName | SJPTS_AutoCorpusExact | Bob")]
    public void FormatComment_WritesTheDocumentedShape(SkyPatcherNameKind kind, string notes, string original, string expected)
    {
        Assert.Equal(expected, SkyPatcherOutputFormat.FormatComment(kind, notes, original));
    }

    [Theory]
    [InlineData(SkyPatcherNameKind.FullName, "SJPTS_TranslationLocalLlm", "Fur Coat")]
    [InlineData(SkyPatcherNameKind.ShortName, "", "Bob")]                          // no method recorded
    [InlineData(SkyPatcherNameKind.FullName, "SJPTS_ModifiedByUser", "A | B | C")]   // '|' inside the original
    [InlineData(SkyPatcherNameKind.FullName, "SJPTS_X", " leading and trailing ")]   // the original is kept exactly
    public void ACommentReadsBackToWhatWasWritten(SkyPatcherNameKind kind, string notes, string original)
    {
        var comment = SkyPatcherOutputFormat.FormatComment(kind, notes, original);

        Assert.True(SkyPatcherOutputFormat.TryParseComment(comment, out var parsedKind, out var parsedNotes, out var parsedOriginal));
        Assert.Equal(kind, parsedKind);
        Assert.Equal(notes, parsedNotes);
        Assert.Equal(original, parsedOriginal);
    }

    [Theory]
    [InlineData("; Generated by SJPTS")]
    [InlineData("; just a comment")]
    [InlineData("filterByArmors=Skyrim.esm|1:fullName=~X~")]
    [InlineData("; SJPTS bogusKind | n | text")]
    [InlineData("; SJPTS fullName | only two fields")]
    [InlineData("")]
    public void ALineThatIsNotOneOfOurNameComments_IsNotParsed(string line)
    {
        Assert.False(SkyPatcherOutputFormat.TryParseComment(line, out _, out _, out _));
    }

    [Fact]
    public void OurOutputFolder_IsNamedSoItSortsAfterEverything()
    {
        // 'z' sorts last in SkyPatcher's 0->z file order (grammar §2); confirmed in game to apply after
        // files in the type folder root and in other mods' subfolders.
        Assert.Equal("zzz_SJPTS", SkyPatcherOutputFormat.FolderName);
    }
}
