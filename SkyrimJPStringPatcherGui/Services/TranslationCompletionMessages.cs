namespace SkyrimJPStringPatcherGui.Services;

/// <summary>
/// 2026-09-13: 「翻訳実行」完了後、未翻訳が残っているかどうかで出し分ける
/// メッセージボックスの文言を、プラグイン翻訳（MainForm.cs）・Interface翻訳
/// （InterfaceTextPanel.cs）で共通化したもの。
///
/// 以前はプラグイン翻訳側だけ「⑤/⑥を有効にしたのに1件も解決できなかった
/// 場合のみ」警告する厳しい条件（CountResolvedByMethod(...) == 0）を使って
/// いたが、これだと打ち切り等でバッチの一部だけが失敗したケース（1件以上は
/// 解決済み）を見逃す上、「1件も翻訳できませんでした」という文言が部分成功
/// の実態と食い違う。一方、意味翻訳・音訳分解・簡易名前解決等の存在により
/// プラグイン翻訳が完全に（未翻訳0件で）終わることはそもそも稀なので、条件を
/// 単純に「1件でも未解決が残っていれば警告」にすると、ほぼ毎回警告が出て
/// しまい「設定に問題がある可能性があります」という強い決めつけ文言のままでは
/// オオカミ少年になる。
///
/// そこで、文言自体を「よくあること」として中立化し（設定の問題だけでなく、
/// モデルの応答形式・出力トークン上限打ち切り等、複数の原因を並列に例示）、
/// 条件も両パイプラインとも「1件でも未解決が残っていれば」に統一した。
/// </summary>
public static class TranslationCompletionMessages
{
    public const string IncompleteTitle = "未翻訳のケースがあります";

    public const string IncompleteBody =
        "未翻訳のケースがあります。翻訳内容を確認してください。\n\n" +
        "主な原因として、以下のようなケースが考えられます:\n" +
        "・モデルが期待した形式で応答を返せなかった\n" +
        "・モデルの応答が出力トークン数の上限で打ち切られた\n" +
        "・ローカルLLM/生成AIサーバーへの接続に問題がある\n\n" +
        "ローカルLLM/生成AIの応答は毎回安定するとは限らないため、「翻訳実行」を複数回行うと解決することもあります。\n" +
        "詳細な理由は実行ログウィンドウ・ログファイルをご確認ください。";
}
